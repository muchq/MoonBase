absl::Status PgGameSink::Write(absl::Span<const IndexedGame> games) {
  if (games.empty()) return absl::OkStatus();

  std::vector<const IndexedGame*> ordered;
  ordered.reserve(games.size());
  for (const IndexedGame& game : games) ordered.push_back(&game);
  std::sort(ordered.begin(), ordered.end(),
            [](const IndexedGame* a, const IndexedGame* b) { return a->url < b->url; });

  bool still_owner = false;
  const absl::Status written = client_.InTransaction([&](pg::Transaction& tx) -> absl::Status {
    const absl::StatusOr<pg::Result> owner = tx.Exec(kFence, {request_id_, owner_});
    if (!owner.ok()) return owner.status();
    if (owner->rows() == 0) return absl::OkStatus();
    still_owner = true;

    for (const IndexedGame* game : ordered) {
      const absl::StatusOr<pg::Result> upserted =
          tx.Exec(kUpsertGame, {request_id_, game->url, game->platform, game->white_username,
                                game->black_username, OptionalNumber(game->white_elo),
                                OptionalNumber(game->black_elo), game->white_title,
                                game->black_title, game->time_class, game->eco, game->opening_name,
                                game->opening_family, game->result, OptionalNumber(game->played_at),
                                OptionalNumber(game->num_moves), game->pgn});
      if (!upserted.ok()) return upserted.status();
    }

    for (const IndexedGame* game : ordered) {
      const absl::StatusOr<pg::Result> locked = tx.Exec(kLockGames, {game->url});
      if (!locked.ok()) return locked.status();
      // Deleted before inserting because the upsert has no key to replace
      // on: motif_occurrences has no uniqueness beyond a random id, so a
      // reindexed game would otherwise keep both copies. A game whose
      // second look found no motifs must still lose the rows it had.
      const absl::StatusOr<pg::Result> deleted = tx.Exec(kDeleteOccurrences, {game->url});
      if (!deleted.ok()) return deleted.status();

      for (const one_d4::MotifOccurrence& occurrence : game->occurrences) {
        const absl::StatusOr<pg::Result> inserted = tx.Exec(
            kInsertOccurrence,
            {game->url, std::string(one_d4::ToString(occurrence.motif)), Number(occurrence.ply),
             std::string(chess_cpp::ToString(occurrence.side)), Number(occurrence.move_number),
             occurrence.description, Or(occurrence.moved_piece), Or(occurrence.attacker),
             Or(occurrence.target), Bool(occurrence.is_discovered), Bool(occurrence.is_mate),
             PinTypeOf(occurrence)});
        if (!inserted.ok()) return inserted.status();
      }
    }
    return absl::OkStatus();
  });

  if (!written.ok()) return written;
  if (!still_owner) {
    return absl::FailedPreconditionError(
        absl::StrCat("request ", request_id_, " no longer names ", owner_));
  }
  return absl::OkStatus();
}

